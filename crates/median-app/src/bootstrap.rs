use median_ipc::{
    AccountChanged, AgentChanged, BookMoved, CatalogChanged, CollectorChanged, GameChanged,
    InventoryChanged, MarketChanged, MembershipChanged, PolicyChanged, PricesChanged,
    QuarantineChanged, QuotesChanged, Rang, SettingsChanged, TasksChanged, UpdateProgressed,
    WorldChanged,
};

use crate::commands;

/// Builds the tauri-specta registry of every IPC command and event.
pub fn specta_builder() -> tauri_specta::Builder<tauri::Wry> {
    tauri_specta::Builder::<tauri::Wry>::new()
        .commands(tauri_specta::collect_commands![
            commands::set_locale,
            commands::set_accent,
            commands::get_build,
            commands::check_update,
            commands::install_update,
            commands::set_update_channel,
            commands::update_settled,
            commands::sync_catalog,
            commands::get_game_data,
            commands::get_collector_folder,
            commands::show_collector_folder,
            commands::show_log_folder,
            commands::get_state,
            commands::get_inventory,
            commands::get_icons,
            commands::get_nodes,
            commands::get_goods,
            commands::get_mastery,
            commands::get_catalogue,
            commands::get_tree,
            commands::get_roadmap,
            commands::get_haul,
            commands::restart_haul,
            commands::get_syndicates,
            commands::set_planned,
            commands::set_favourite,
            commands::get_favourites,
            commands::set_roadmap,
            commands::clear_roadmap,
            commands::set_part_choice,
            commands::get_other_name,
            commands::get_coins,
            commands::get_card,
            commands::get_riven_appraisal,
            commands::get_riven_band,
            commands::get_riven_ceiling,
            commands::get_riven_demand,
            commands::get_riven_rolls,
            commands::get_riven_choices,
            commands::put_up_riven,
            commands::get_own_auctions,
            commands::change_riven_auction,
            commands::close_riven_auction,
            commands::open_auction,
            commands::get_riven_names,
            commands::get_taxonomy,
            commands::get_quotes,
            commands::get_sets,
            commands::get_relics,
            commands::get_relics_of,
            commands::get_search,
            commands::get_prices,
            commands::get_set_prices,
            commands::get_listings,
            commands::set_shown,
            commands::get_curve,
            commands::sign_in,
            commands::sign_out,
            commands::set_status_auto,
            commands::set_status,
            commands::get_orders,
            commands::get_positions,
            commands::refresh_orders,
            commands::amend_order,
            commands::withdraw_orders,
            commands::show_orders,
            commands::place_order,
            commands::record_exchange,
            commands::hand_to_agent,
            commands::hand_order_to_agent,
            commands::release_position,
            commands::record_riven_buy,
            commands::dismiss_riven_pick,
            commands::record_riven_sale,
            commands::get_riven_buys,
            commands::get_figures,
            commands::get_scorecard,
            commands::set_policy,
            commands::set_alert,
            commands::set_watch,
            commands::get_swaps,
            commands::set_agent,
            commands::window_ready
        ])
        .events(tauri_specta::collect_events![
            AccountChanged,
            CatalogChanged,
            CollectorChanged,
            InventoryChanged,
            MarketChanged,
            MembershipChanged,
            PricesChanged,
            QuotesChanged,
            BookMoved,
            PolicyChanged,
            AgentChanged,
            GameChanged,
            TasksChanged,
            QuarantineChanged,
            SettingsChanged,
            WorldChanged,
            UpdateProgressed,
            Rang
        ])
        // Seconds the game may run before a missing collector counts as a problem: the same
        // silence after which a connected collector counts as gone.
        .constant(
            "COLLECTOR_GRACE_S",
            crate::collector::SILENCE.as_secs() as u32,
        )
        // Accent codes `set_accent` accepts, in the order the settings offer them.
        .constant(
            "ACCENTS",
            median_core::Accent::ALL.map(median_core::Accent::as_code),
        )
}
